/**
 * Reusable 3D Room Template:
 * Dynamically constructs additional 3D wings for newly created categories.
 */
export function buildDynamicCastleRooms(dynamicCategories = [], existingPosts = []) {
  const rooms = [...BASE_CASTLE_ROOMS];
  const existingCatIds = new Set(rooms.map(r => r.categoryId).filter(Boolean));

  // Determine offsets for new dynamic wings
  let dynamicIndex = 0;
  for (const cat of dynamicCategories) {
    if (!existingCatIds.has(cat.id)) {
      // Find matching post if any
      const matchingPost = existingPosts.find(p => p.categoryId === cat.id);
      const angle = (dynamicIndex * Math.PI) / 3;
      const distance = 92 + (Math.floor(dynamicIndex / 6) * 30);
      const nx = Math.round(Math.cos(angle) * distance);
      const nz = Math.round(Math.sin(angle) * distance);

      rooms.push({
        id: `room-${cat.id}`,
        name: `${cat.name} Hall`,
        category: cat.name,
        categoryId: cat.id,
        description: cat.description || `The dedicated ${cat.name} hall of the castle.`,
        x: nx,
        z: nz,
        width: 22,
        depth: 22,
        height: 14,
        floorColor: 0x151c28,
        wallColor: 0x10141f,
        accentColor: cat.color || '#38BDF8',
        lightColor: 0x93c5fd,
        lightIntensity: 1.5,
        pedestalPos: [nx, 0, nz - 2],
        articleId: matchingPost ? matchingPost.id : 'post-vaults',
        isDynamic: true
      });
      dynamicIndex++;
    }
  }

  return rooms;
}
